-- CineMatch AI Supabase schema
-- Import the trained records into movies after running training/train_recommender.py.

create table if not exists movies (
  tmdb_id bigint primary key,
  title text not null,
  year integer,
  runtime integer,
  rating numeric(3,1),
  genres jsonb default '[]'::jsonb,
  moods jsonb default '[]'::jsonb,
  narrative_vectors jsonb default '[]'::jsonb,
  social_dynamics jsonb default '[]'::jsonb,
  languages jsonb default '[]'::jsonb,
  original_language text,
  spoken_languages jsonb default '[]'::jsonb,
  overview text,
  keywords jsonb default '[]'::jsonb,
  poster_path text,
  backdrop_path text,
  directors text,
  cast text,
  mooduel jsonb default '{}'::jsonb,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists movies_rating_idx on movies (rating desc);
create index if not exists movies_runtime_idx on movies (runtime);
create index if not exists movies_original_language_idx on movies (original_language);
create index if not exists movies_genres_gin_idx on movies using gin (genres);
create index if not exists movies_moods_gin_idx on movies using gin (moods);
create index if not exists movies_narrative_gin_idx on movies using gin (narrative_vectors);
create index if not exists movies_social_gin_idx on movies using gin (social_dynamics);
create index if not exists movies_languages_gin_idx on movies using gin (languages);

-- User feedback can later be used to train a collaborative re-ranker.
create table if not exists user_movie_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  tmdb_id bigint not null references movies(tmdb_id) on delete cascade,
  feedback text not null check (feedback in ('liked','disliked','watched','skipped')),
  created_at timestamptz default now()
);
